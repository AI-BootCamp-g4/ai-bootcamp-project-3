FA = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def fa(x) -> str:
    return str(x).translate(FA).replace(".", "٫")


def rows(d: Path, name: str) -> list[dict]:
    p = d / f"{name}.jsonl"
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []


def rate(rs, key) -> str:
    v = [r[key] for r in rs if r.get(key) is not None]
    return f"{fa(round(100 * sum(v) / len(v)))}٪ ({fa(sum(v))} از {fa(len(v))})" if v else "-"


def pct(rs, key) -> str:
    v = [r[key] for r in rs if isinstance(r.get(key), (int, float))]
    return f"{fa(round(100 * statistics.mean(v)))}٪" if v else "-"


def mean(rs, key, judge=False, nd=1) -> str:
    v = [r["judge"][key] for r in rs if isinstance((r.get("judge") or {}).get(key), (int, float))] if judge \
        else [r[key] for r in rs if isinstance(r.get(key), (int, float))]
    return fa(round(statistics.mean(v), nd)) if v else "-"


def median(rs, key) -> str:
    v = [r[key] for r in rs if isinstance(r.get(key), (int, float))]
    return fa(round(statistics.median(v), 1)) if v else "-"


def table(head: list[str], body: list[list[str]]) -> str:
    h = "".join(f"<th>{x}</th>" for x in head)
    b = "".join("<tr>" + "".join(f"<td>{x}</td>" for x in r) + "</tr>" for r in body)
    return f"<table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>"


def page(title: str, sub: str, summary: str, body: str) -> str:
    return f"""<section class="page"><div class="kicker">پروژهٔ سوم · گروه چهار · گزارش پیشرفت</div>
<h1>{title}</h1><div class="sub">{sub}</div>
<div class="sum"><b>خلاصه</b><p>{summary}</p></div>{body}</section>"""


def note(title: str, text: str) -> str:
    return f'<div class="note"><b>{title}</b><p>{text}</p></div>'


def step(n: int, title: str, how: str, method: str, out: str) -> str:
    return (f'<div class="step"><div class="n">{fa(n)}</div><div><b>{title}</b><p>{how}</p>'
            f'<p class="m"><span>روش:</span> {method}</p><p class="o"><span>خروجی:</span> {out}</p></div></div>')


def file_row(name: str, job: str, method: str, out: str) -> list[str]:
    return [f'<span dir="ltr" class="f">{name}</span>', job, method, out]


